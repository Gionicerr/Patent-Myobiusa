class UniversalAssistant:
    """Универсальный вопросно-ответный агент с автоматическим подбором модели"""

    def __init__(self):
        print("\n🔍 Инициализация универсального ассистента...")

        # 1. Найти работающую модель
        working_model = self._find_working_model()
        print(f"✅ Используем модель: {working_model}")


        # 2. Создать модель с найденным именем
        self.model = ChatOpenAI(
            model=working_model,
            temperature=0.5,
            openai_api_key=os.environ["OPENAI_API_KEY"],
            openai_api_base=os.environ["OPENAI_API_BASE"],
            max_retries=2,
            request_timeout=30
        )

        # 3. Определить инструменты
        self.tools = [
            search_legal_info,
            check_patent_requirements,
            get_legal_forms,
            calculate_deadlines,
            suggest_legal_consultation,
            general_knowledge_search
        ]

        self.memory = MemorySaver()

        # 4. Системный промпт
        self.system_prompt = """
Ты — Универсальный Ассистент, который может отвечать на самые разные вопросы.

Твои основные особенности:
- Можешь общаться на любые темы
- Имеешь глубокие знания в области юридических вопросов, интеллектуальной собственности и патентного права
- Можешь поддерживать разговор на общие темы: технологии, наука, культура, повседневные вопросы
- Всегда стараешься быть полезным и давать точные ответы

Принципы работы:
1. Будь дружелюбным, терпеливым и отзывчивым
2. Если не знаешь ответа - честно говори об этом
3. Для юридических вопросов давай точные и проверенные консультации
4. Для сложных юридических вопросов рекомендуй обращаться к профессиональным юристам
5. Поддерживай естественную беседу на любые темы

Структура ответа:
1. Понятный и прямой ответ на вопрос
2. Дополнительная информация, если она уместна
3. Предложение помощи по другим вопросам
"""

        # 5. Создать агента с обработкой ошибок
        try:
            self.agent = create_react_agent(
                model=self.model,
                tools=self.tools,
                checkpointer=self.memory,
                prompt=self.system_prompt
            )
            print("✅ Реактивный агент успешно создан!")
            self.agent_type = "react_agent"
        except Exception as e:
            print(f"⚠️  Не удалось создать реактивного агента: {str(e)[:100]}...")
            print("Использую простую модель без инструментов...")
            self.agent_type = "simple_model"
            print("✅ Простая модель успешно создана!")

    def _find_working_model(self):
        """Автоматический подбор работающей модели"""
        print("🔎 Поиск доступной модели...")

        # Получить список доступных моделей
        available_models = check_available_models()

        if not available_models:
            print("⚠️  Не удалось получить список моделей, использую стандартный набор")
            available_models = ["gpt-3.5-turbo", "gpt-4", "sbert-ru-sentiment-rusentiment"]

        # Протестировать каждую модель
        for model_name in available_models:
            try:
                print(f"  Пробую модель: {model_name}")
                test_model = ChatOpenAI(
                    model=model_name,
                    temperature=0.1,
                    openai_api_key=os.environ["OPENAI_API_KEY"],
                    openai_api_base=os.environ["OPENAI_API_BASE"],
                    max_retries=1,
                    request_timeout=10
                )
                # Простой тестовый запрос
                test_response = test_model.invoke("Привет")
                print(f"  ✅ Модель {model_name} работает!")
                return model_name
            except Exception as e:
                print(f"  ❌ Модель {model_name} не работает: {str(e)[:80]}...")
                continue

        # Если ни одна модель не сработала
        print("⚠️  Не найдено работающих моделей, использую gpt-3.5-turbo по умолчанию")
        return "gpt-3.5-turbo"

    def process_message(self, user_input: str, thread_id: str = "chat-session-1") -> str:
        """Обрабатывает сообщение пользователя и возвращает ответ"""


        try:
            if self.agent_type == "react_agent":
                config = {"configurable": {"thread_id": thread_id}}
                response = self.agent.invoke(
                    {"messages": [{"role": "user", "content": user_input}]},
                    config=config
                )
                last_message = response["messages"][-1]
                return last_message.content
            else:
                # Для простой модели
                response = self.model.invoke(user_input)
                return response.content

        except Exception as e:
            return f"Произошла ошибка при обработке запроса: {str(e)}\n\nПопробуйте переформулировать вопрос или обратиться к патентному поверенному для сложных юридических вопросов."


