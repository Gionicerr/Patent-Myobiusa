def run_chat():
    """Запускает чат-сессию"""
    print("=" * 60)
    print("              УНИВЕРСАЛЬНЫЙ АССИСТЕНТ")
    print("              (с автоподбором модели)")
    print("=" * 60)

    assistant = create_assistant()

    print("\n" + "=" * 60)
    print("💬 Ассистент готов к работе!")
    print(f"📊 Тип агента: {assistant.agent_type}")
    print("=" * 60)
    print("\nПривет, чем я могу тебе помочь?\n")
    print("Доступные команды:")
    print("  - 'выход', 'exit', 'quit' - завершить работу")
    print("  - Ctrl+C - аварийное завершение")
    print("-" * 60 + "\n")

    while True:
        try:
            user_input = input("💬 Твое сообщение: ").strip()

            if user_input.lower() in ['выход', 'exit', 'quit']:
                print("\n✅ Было приятно пообщаться! Возвращайся, если будут еще вопросы!")
                break

            if not user_input:
                continue

            print("\n🤔 Думаю...\n")

            response = assistant.process_message(user_input)
            print(f"💡 {response}\n")
            print("-" * 60 + "\n")

        except KeyboardInterrupt:
            print("\n\n✅ Диалог завершен. Хорошего дня!")
            break
        except Exception as e:
            print(f"❌ Неожиданная ошибка: {str(e)}")
            print("Попробуй задать вопрос по-другому.\n")


